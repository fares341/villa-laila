export const STRINGS: Record<Lang, Dict> = { en, es, fr, ar };

export function t(lang: Lang | null | undefined, key: string, vars: Record<string, string | number> = {}): string {
  const l = lang && STRINGS[lang] ? lang : 'en';
  let s = STRINGS[l][key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
export const isLang = (x: unknown): x is Lang => typeof x === 'string' && (LANGS as string[]).includes(x);
